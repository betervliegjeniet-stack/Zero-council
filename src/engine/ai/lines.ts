/** A flavor line for this seat, picked deterministically for the state. */
export function line(s: GameState, seat: Seat, kind: LineKind, names: { you?: string; target?: string } = {}, salt = ''): string {
  const pool = LINES[s.players[seat]!.factionId][kind];
  return pick(aiRng(s, seat, `line${kind}${salt}`), pool)
    .replaceAll('{target}', names.target ?? 'them')
    .replaceAll('{you}', names.you ?? 'Councilor');
}
